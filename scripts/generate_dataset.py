"""
generate_dataset.py
===================
Synthetic Dataset Generator for the Ground Truth Corpus

This script produces the entire synthetic document corpus used as the
evaluation foundation for all 50+ attack experiments in Phases 2–4.
Every record is fictional — generated by the Faker library — so no
real individual's data is ever at risk. The corpus is divided into
four document classes, each targeting a different segment of the
threat model defined in Chapter 2 of the project:

    Class 1 — HR Employee Records (100 documents)
        Contains PII at every severity level (2 through 5) as defined
        in Table 6.1 of the Threat Model document. These records are
        the primary target for Profile 1 (Internal Employee) and
        Profile 2 (External Adversary) attack scenarios.

    Class 2 — System Configuration Files (5 documents)
        Contains API keys, JWT tokens, database connection strings,
        system prompts, and private key snippets — all severity 5
        (Critical) system secrets. These are the primary target for
        Profile 3 (Privileged Admin) context poisoning and config
        exfiltration attacks.

    Class 3 — Internal Memos (20 documents)
        Free-text memos that reference real employees from Class 1
        by name, salary, and medical condition. These test whether
        the evaluation engine can detect PII embedded in unstructured
        narrative text. They also provide material for Linkability
        attacks (LINDDUN category 1).

    Class 4 — Medical Reports (30 documents)
        Linked to specific employee records via employee_ref. These
        contain GDPR Article 9 special-category health data: diagnoses,
        prescriptions, treating physicians, and work restrictions.

REPRODUCIBILITY
---------------
Both random.seed(seed) and Faker.seed(seed) are called at the start of
generate_corpus(). The default seed is CORPUS_SEED = 42, guaranteeing the
exact same 155 documents on every run and every machine. Pass --seed N on
the command line for distinct-but-reproducible corpora in Monte Carlo runs.

OUTPUT FILES (written to data/ground_truth/)
--------------------------------------------
    ground_truth.json       — Full corpus with metadata header
    ground_truth_index.json — Flat dictionary keyed by document_id
    
"""

