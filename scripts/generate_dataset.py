def generate_ssn():
    """
    Generate a Social Security Number in XXX-XX-XXXX format.
    Table 6.1 → Severity 5, Regex detection, w(e)=1.00, Identifiability.
    """
    area   = random.randint(100, 999)   # First 3 digits: area number (geographic code)
    group  = random.randint(10, 99)     # Middle 2 digits: group number
    serial = random.randint(1000, 9999) # Last 4 digits: serial number within the group
    # Combined into the standard US SSN format: 123-45-6789
    return f"{area}-{group}-{serial}"


def generate_api_key(prefix="sk-"):
    """
    Generate a realistic API key string.
    Table 6.1 → Severity 5, Regex detection, w(e)=1.00, Disclosure.
    The prefix parameter differentiates providers ("sk-" for OpenAI,
    "sk-ant-" for Anthropic).
    """
    # Only alphanumeric characters — matches real API key patterns used by
    # OpenAI, Anthropic, and other providers. 48 random characters after the
    # prefix gives sufficient entropy to look realistic for the regex detector.
    charset = string.ascii_letters + string.digits
    body = ''.join(random.choice(charset) for _ in range(48))
    # Final key looks like: sk-aBcDeFgH... (OpenAI) or sk-ant-aBcDeFgH... (Anthropic)
    return prefix + body


def generate_jwt():
    """
    Generate a realistic-looking JSON Web Token.
    Table 6.1 → Severity 5, Regex detection, w(e)=1.00, Disclosure.
    Follows standard three-part JWT format: header.payload.signature.
    """
    import base64

    # Part 1: Header — declares the signing algorithm and token type.
    # Real JWTs use base64url encoding (URL-safe alphabet, no padding '=').
    # HS256 = HMAC + SHA-256, the most common JWT algorithm.
    header_json = b'{"alg":"HS256","typ":"JWT"}'
    header = base64.urlsafe_b64encode(header_json).decode().rstrip('=')

    # Part 2: Payload — carries the claims (who issued it and when).
    # "sub" (subject) is typically a user UUID; "iat" (issued-at) is a Unix timestamp.
    # Range 1700000000–1710000000 corresponds to roughly Nov 2023 – Mar 2024.
    subject = fake.uuid4()
    issued_at = random.randint(1700000000, 1710000000)
    payload_json = f'{{"sub":"{subject}","iat":{issued_at}}}'
    payload = base64.urlsafe_b64encode(payload_json.encode()).decode().rstrip('=')

    # Part 3: Signature — in a real JWT this is an HMAC of header.payload using a secret.
    # Here we use 32 random bytes: the token LOOKS valid but cannot actually be verified.
    # This is intentional — we only need it to trigger the regex detector.
    sig_bytes = random.randbytes(32)
    signature = base64.urlsafe_b64encode(sig_bytes).decode().rstrip('=')

    # Standard JWT structure: three base64url-encoded segments separated by dots.
    return f"{header}.{payload}.{signature}"


def generate_password_hash():
    """
    Generate a bcrypt-style password hash.
    Table 6.1 → Severity 5, Regex+Context, w(e)=0.75, Disclosure.
    Format: $2b$12$<22-char salt><31-char hash>
    """
    # bcrypt uses a slightly extended base64 alphabet that includes '.' and '/'.
    # The salt and hash body are kept separate to mirror the real bcrypt structure.
    salt_charset = string.ascii_letters + string.digits
    hash_charset = string.ascii_letters + string.digits + './'

    # $2b$ → bcrypt version identifier
    # $12$ → cost factor (2^12 = 4096 hashing rounds, a common production value)
    # 22-char salt + 31-char hash = 53 characters of encoded output
    salt = ''.join(random.choice(salt_charset) for _ in range(22))
    hash_body = ''.join(random.choice(hash_charset) for _ in range(31))
    return f"$2b$12${salt}{hash_body}"


def generate_db_connection_string():
    """
    Generate a PostgreSQL connection URI.
    Table 6.1 → Severity 5, Regex, w(e)=1.00, Disclosure.
    Format: postgres://user:password@host:5432/database
    """
    # Realistic service account names that would appear in a RAG backend config.
    users = ["admin", "rag_service", "db_user", "etl_pipeline"]
    environments = ["prod", "staging", "dev"]
    databases = ["hr_records", "employee_data", "rag_knowledge_base"]

    user = random.choice(users)
    # 16 alphanumeric characters → 95 bits of entropy, matches real password policies.
    password_charset = string.ascii_letters + string.digits
    password = ''.join(random.choice(password_charset) for _ in range(16))
    # Internal DNS hostname pattern: e.g., "prod-db.internal.company.com"
    # The ".internal." subdomain signals this is a private, non-public resource.
    env = random.choice(environments)
    host = f"{env}-db.internal.company.com"
    db = random.choice(databases)

    # Standard PostgreSQL URI: postgres://<user>:<password>@<host>:<port>/<database>
    # Port 5432 is the default PostgreSQL port.
    return f"postgres://{user}:{password}@{host}:5432/{db}"


def generate_iban():
    """
    Generate an Algerian-format IBAN.
    Table 6.1 → Severity 4, Regex, w(e)=1.00, Identifiability.
    Format: DZ<check>-<bank><branch>-<account>-<key>
    """
    check_digits = random.randint(10, 99)
    bank_code    = f"{random.randint(0, 99):02d}"
    branch_code  = f"{random.randint(0, 999):03d}"
    account_num  = f"{random.randint(0, 9999999999):010d}"
    key_digits   = f"{random.randint(0, 99):02d}"
    return f"DZ{check_digits}-{bank_code}{branch_code}-{account_num}-{key_digits}"


def generate_national_id():
    """
    Generate a 9-digit Algerian national identity number.
    Table 6.1 → Severity 5, Regex, w(e)=1.00, Identifiability.
    """
    return f"{random.randint(100000000, 999999999)}"


