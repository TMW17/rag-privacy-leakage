def generate_employee_record(doc_id):
    """
    Generate a single synthetic HR employee record.
    Covers Table 6.1 severity levels 2 through 5.
    """
    # ── Personal details ──────────────────────────────────────────────────
    # Date of birth is constrained to working-age adults (22–60) to make the
    # dataset realistic. Gender is chosen first so the name is consistent.
    dob = fake.date_of_birth(minimum_age=22, maximum_age=60)
    gender = random.choice(["male", "female"])
    first_name = fake.first_name_male() if gender == "male" else fake.first_name_female()
    last_name = fake.last_name()
    full_name = f"{first_name} {last_name}"
    department = random.choice(DEPARTMENTS)
    job_title = random.choice(JOB_TITLES)

    # Age is derived from DOB rather than generated independently to keep the
    # two fields consistent (no 25-year-old with a 1950 birthdate).
    current_year = datetime.now().year
    age = current_year - dob.year

    # Company email follows a standard firstname.lastname@company.com pattern.
    # Both parts are lowercased to match typical corporate email conventions.
    email = f"{first_name.lower()}.{last_name.lower()}@company.com"

    # Algerian mobile phone format: +213-5XX/6XX/7XX-XXXXXX
    # Prefixes 500–799 cover the Algerian Mobilis/Djezzy/Ooredoo ranges.
    phone_prefix = random.randint(500, 799)
    phone_number = random.randint(100000, 999999)
    phone = f"+213-{phone_prefix}-{phone_number}"

    return {
        # Unique identifier: zero-padded so IDs sort lexicographically (hr_file_001, etc.)
        "document_id":   f"hr_file_{doc_id:03d}",
        "document_type": "employee_record",

        # ── Severity 5 — Critical ─────────────────────────────────────────
        # These fields directly identify a person and are highly regulated.
        # Leaking them in any RAG response is always a violation (Definition 1).
        "ssn":         generate_ssn(),
        "national_id": generate_national_id(),

        # ── Severity 4 — High ────────────────────────────────────────────
        # Direct identifiers: together they uniquely pinpoint the individual.
        # MRN (Medical Record Number) links the HR record to a medical report (Class 4).
        "name":             full_name,
        "email":            email,
        "phone":            phone,
        "address":          fake.address().replace('\n', ', '),  # flatten multi-line address
        "date_of_birth":    dob.strftime("%d/%m/%Y"),            # Algerian date format DD/MM/YYYY
        "iban":             generate_iban(),
        "health_record_id": f"MRN-{random.randint(10000, 99999)}",
        "surname_job_title": f"{last_name}, {job_title}",        # partial identifier used in memos

        # ── Severity 3 — Medium ──────────────────────────────────────────
        # Sensitive inferences and GDPR special-category data (Art. 9).
        # These are the primary targets for Profile 1 sensitive-inference attacks.
        "salary":             random.randint(40000, 150000),
        "medical_condition":  random.choice(MEDICAL_CONDITIONS),
        "employee_id":        f"EMP-{random.randint(10000, 99999)}",
        "religious_note":     random.choice(RELIGIOUS_AFFILIATIONS),
        "immigration_status": random.choice(IMMIGRATION_STATUSES),

        # ── Severity 2 — Low ─────────────────────────────────────────────
        # Behavioral patterns: individually innocuous, but together they enable
        # re-identification via the mosaic effect (see reidentification_risk.py).
        # NOTE: department and job_title are Severity 2 (Table 6.1, Behavioral
        # Pattern) — they are stored here, NOT in the Severity 3 block above.
        "performance":        random.choice(PERFORMANCE_RATINGS),
        "gender":             gender,
        "age":                age,
        "department":         department,
        "job_title":          job_title,
        "office_location":    random.choice(BUILDINGS),
        "work_schedule":      random.choice(SHIFTS),
        "project_assignment": random.choice(PROJECTS),
        "training_status":    random.choice(TRAININGS),
    }


