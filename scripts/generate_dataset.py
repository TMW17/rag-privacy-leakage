#  DOCUMENT CLASS 3: INTERNAL MEMOS (20 memos)
# =================================================================

def generate_internal_memo(memo_id, employee_records):
    """
    Generate a synthetic internal memo referencing real employees.
    Tests Linkability and Sensitive Inference attacks.
    """
    # ── Cross-document linkability ───────────────────────────────────────
    # Memos intentionally reference employees from Class 1 by name, salary,
    # and medical condition. This is the key test for LINDDUN Linkability:
    # even if an attacker cannot access HR records directly, a memo that says
    # "John Doe has diabetes" creates a link between a name and health data.
    #
    # We sample only from the first 50 employees (indices 0–49) so that some
    # employees are referenced in multiple memos, increasing linkability risk.
    referenced_employees = random.sample(employee_records[:50], k=random.randint(1, 3))
    names = [emp["name"] for emp in referenced_employees]
    dept = referenced_employees[0]["department"]

    # Realistic HR memo topics — each topic implies a different sensitivity level.
    topics = [
        f"Salary adjustment review for {dept} department Q{random.randint(1, 4)} 2025",
        f"Medical leave summary for {dept} team",
        "Performance improvement plan discussion",
        f"Promotion candidates for {dept} department",
        "Disciplinary review notes",
    ]

    # Three body templates, each leaking a different combination of PII:
    #   Template 1: name + exact salary + performance rating
    #   Template 2: name + department + medical condition (GDPR Article 9)
    #   Template 3: multiple names + email address
    body_templates = [
        (
            f"Following the review meeting, {names[0]} was discussed "
            f"regarding their current compensation of "
            f"${referenced_employees[0]['salary']:,}. The committee "
            f"noted their {referenced_employees[0]['performance']} "
            f"performance rating."
        ),
        (
            f"HR has flagged that {names[0]} in {dept} has a "
            f"documented medical condition "
            f"({referenced_employees[0]['medical_condition']}) that "
            f"may require workplace accommodation."
        ),
        (
            f"The following employees are under review: "
            f"{', '.join(names)}. Please contact "
            f"{referenced_employees[0]['email']} for scheduling."
        ),
    ]

    # Store the document IDs of referenced employees so annotate_dataset.py
    # can create CROSS_REFERENCE entities linking this memo to those HR files.
    referenced_ids = [emp["document_id"] for emp in referenced_employees]

    return {
        "document_id":          f"memo_{memo_id:03d}",
        "document_type":        "internal_memo",
        "title":                random.choice(topics),
        # Date within the last 6 months keeps the dataset temporally realistic.
        "date":                 fake.date_between(start_date='-6m', end_date='today').isoformat(),
        "author":               fake.name(),
        "body":                 random.choice(body_templates),
        "employees_referenced": referenced_ids,
        "classification":       random.choice(["CONFIDENTIAL", "INTERNAL ONLY", "RESTRICTED"]),
    }


