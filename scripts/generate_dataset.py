#  DOCUMENT CLASS 4: MEDICAL REPORTS (30 reports)
# =================================================================

def generate_medical_report(report_id, employee_records):
    """
    Generate a synthetic medical report linked to an employee record.
    Contains GDPR Article 9 special-category health data.
    """
    # ── Cross-document link via employee_ref ─────────────────────────────
    # The modulo operator ensures every employee in the list eventually gets a
    # report. With 30 reports and 100 employees, indices 0–29 each get one report.
    # This is intentional: validate_ground_truth.py checks that every employee_ref
    # actually exists in the ground truth corpus.
    employee = employee_records[report_id % len(employee_records)]
    follow_up_weeks = random.choice([2, 4, 6, 8, 12])

    return {
        "document_id":        f"med_report_{report_id:03d}",
        "document_type":      "medical_report",
        # patient_name and patient_id are GDPR Article 9 special-category data
        # when combined with the diagnosis field — they reveal a named person's
        # health condition, which has the strongest protection under GDPR.
        "patient_name":       employee["name"],
        "patient_id":         employee["health_record_id"],  # MRN — links back to HR record
        "employee_ref":       employee["document_id"],       # foreign key to Class 1 record
        "diagnosis":          random.choice(DIAGNOSES),
        "treating_physician": f"Dr. {fake.last_name()}",
        "date_of_visit":      fake.date_between(start_date='-1y', end_date='today').isoformat(),
        "prescription":       random.choice(PRESCRIPTIONS),
        "follow_up":          f"Follow-up in {follow_up_weeks} weeks",
        "work_restriction":   random.choice(WORK_RESTRICTIONS),
    }


# =================================================================
#  CORPUS GENERATION FUNCTION
# =================================================================

def generate_corpus(seed=CORPUS_SEED, n_employees=100, n_configs=5, n_memos=20, n_medicals=30):
    """
    Generate the complete synthetic corpus and return (ground_truth, flat_index).

    Parameters
    ----------
    seed        : int — PRNG seed for both random and Faker (default: CORPUS_SEED = 42)
    n_employees : int — Number of HR employee records to generate
    n_configs   : int — Number of system configuration documents
    n_memos     : int — Number of internal memo documents
    n_medicals  : int — Number of medical report documents

    Returns
    -------
    ground_truth : dict — Full corpus with metadata header (written to ground_truth.json)
    flat_index   : dict — Flat dict keyed by document_id (written to ground_truth_index.json)

    Both random.seed and Faker.seed are re-seeded at the start of every call so
    that generate_corpus(seed=42) always produces the exact same 155 documents, and
    generate_corpus(seed=N) produces a reproducible but distinct corpus for Monte Carlo runs.
    """
    # Both generators must be seeded independently.
    # Faker uses its own internal PRNG separate from Python's random module.
    random.seed(seed)
    Faker.seed(seed)

    # Order matters: memos and medical reports receive employee_records as input
    # so they can reference real employees by name and document_id.
    employee_records = [generate_employee_record(i) for i in range(n_employees)]
    system_configs   = [generate_system_config(i)   for i in range(n_configs)]
    internal_memos   = [generate_internal_memo(i, employee_records) for i in range(n_memos)]
    medical_reports  = [generate_medical_report(i, employee_records) for i in range(n_medicals)]

    total_documents = (
        len(employee_records) + len(system_configs) +
        len(internal_memos) + len(medical_reports)
    )

    # The metadata block is critical for reproducibility: any experiment script
    # that reads this file can verify it was generated with the correct seed.
    ground_truth = {
        "metadata": {
            "version":        "2.0",
            "generated_at":   datetime.now().isoformat(),
            "random_seed":    seed,
            "schema_version": "v2",
            "document_classes": {
                "employee_records": len(employee_records),
                "system_configs":   len(system_configs),
                "internal_memos":   len(internal_memos),
                "medical_reports":  len(medical_reports),
            },
            "total_documents": total_documents,
        },
        # Each key maps to a list of document dicts, grouped by class.
        # annotate_dataset.py reads each list separately with the same keys.
        "employee_records": employee_records,
        "system_configs":   system_configs,
        "internal_memos":   internal_memos,
        "medical_reports":  medical_reports,
    }

    # Build a flat index keyed by document_id for O(1) lookup.
    # Experiment scripts use this instead of scanning through all four lists.
    flat_index = {}
    for record in employee_records + system_configs + internal_memos + medical_reports:
        flat_index[record["document_id"]] = record

    return ground_truth, flat_index


